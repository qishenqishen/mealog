import assert from 'node:assert/strict';
import { copyFile, mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';

const base = process.env.MEALOG_URL || 'http://127.0.0.1:8793';
const output = process.env.QA_OUTPUT || 'artifacts/people-media';
await mkdir(output, { recursive: true });
const sources = await mkdtemp(join(tmpdir(), 'mealog-people-qa-'));
const browser = await chromium.launch({ channel: process.env.CHROME_CHANNEL || 'chrome', headless: true });
const results = [];
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'en-US' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const state = (name) => page.evaluate((key) => JSON.parse(localStorage.getItem('@mealogue/' + key) || 'null'), name);
const readable = () => page.waitForFunction(() => [...document.images].every((img) => !img.src || (img.complete && img.naturalWidth > 0)));
const shot = (name) => page.screenshot({ path: `${output}/${name}.png` });
const pass = (test, detail) => { results.push({ test, status: 'PASS', detail }); console.log('PASS', test, detail || ''); };

try {
  await page.goto(base + '/people');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('@mealogue/standaloneDemoSession') || 'null')?.complete);
  await page.getByRole('button', { name: 'Add person', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('QA Robin');
  const avatarFile = join(sources, 'avatar-source.jpg');
  await copyFile('assets/demo/meal-photos/blueberry-toast.jpg', avatarFile);
  const avatarChooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Choose library', exact: true }).click();
  await (await avatarChooser).setFiles(avatarFile);
  await page.getByRole('button', { name: 'Save person', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('@mealogue/peopleProfiles') || '[]').some((person) => person.name === 'QA Robin'));
  const person = (await state('peopleProfiles')).find((item) => item.name === 'QA Robin');
  assert(person.id && person.avatarMediaId && person.avatarUrl.startsWith('indexeddb://'));
  await rm(avatarFile);
  await page.goto(base + '/people/' + person.id);
  await page.getByText('QA Robin', { exact: true }).first().waitFor();
  await readable();
  await shot('01-avatar-after-source-deletion');
  await page.getByRole('button', { name: 'Edit person', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).waitFor();
  await readable();
  await page.getByRole('button', { name: 'Save person', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await state('peopleProfiles')).filter((item) => item.name === 'QA Robin').length, 1);
  pass('Person avatar is managed, survives source deletion/reload and remains visible while editing', { personId: person.id, mediaId: person.avatarMediaId });

  await page.goto(base + '/add');
  await page.getByLabel('Meal name', { exact: true }).fill('A shared table with Robin');
  await page.getByRole('button', { name: 'Toast', exact: true }).click();
  await page.getByRole('button', { name: 'Add people at this meal', exact: true }).click();
  await page.getByRole('checkbox', { name: /QA Robin/ }).first().click();
  await page.getByText('Add to this meal', { exact: true }).click();
  await page.getByRole('button', { name: 'Save meal memory', exact: true }).click();
  await page.waitForURL(/\/meal\//);
  const meal = (await state('meals')).find((item) => item.title === 'A shared table with Robin');
  const sharedFile = join(sources, 'shared-source.jpg');
  await copyFile('assets/demo/meal-photos/blueberry-toast.jpg', sharedFile);
  const sharedChooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Choose photo together', exact: true }).click();
  await (await sharedChooser).setFiles(sharedFile);
  await page.getByPlaceholder('Caption for this table memory...').fill('A moment together, kept here.');
  await page.getByRole('checkbox', { name: "Use as this meal's cover photo" }).click();
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  await page.getByPlaceholder('Caption for this table memory...').waitFor({ state: 'hidden' });
  const shared = (await state('sharedMealPhotos')).find((item) => item.mealId === meal.id);
  assert(shared.mediaId && shared.imageUrl.startsWith('indexeddb://'));
  assert(shared.taggedPersonIds.includes(person.id));
  assert.equal((await state('meals')).find((item) => item.id === meal.id).photoMediaId, shared.mediaId);
  await rm(sharedFile);
  await page.reload();
  await page.getByText('A moment together, kept here.', { exact: true }).waitFor();
  await readable();
  await shot('02-shared-photo-after-source-deletion');
  pass('Shared upload, tag person, cover photo, source deletion and reload', { mealId: meal.id, mediaId: shared.mediaId });
  await page.goto(base + '/people/' + person.id);
  await page.getByText('A shared table with Robin', { exact: true }).waitFor();
  await readable();
  await shot('03-person-shared-memories');
  pass('Person detail shows the new shared meal, avatar and shared photograph');
  assert.deepEqual(errors, []);
  pass('No uncaught runtime errors');
} catch (error) {
  results.push({ status: 'FAIL', error: error.stack });
  await shot('failure');
  process.exitCode = 1;
  console.error(error);
} finally {
  await writeFile(`${output}/results.json`, JSON.stringify({ base, testedAt: new Date().toISOString(), results }, null, 2));
  await browser.close();
  await rm(sources, { recursive: true, force: true });
}
